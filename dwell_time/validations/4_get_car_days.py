import subprocess
import argparse

def main(args):
    splited_cars = args.cars.split(", ")
    
    for car in splited_cars:
        command = f"find {args.path} -type f -iname '{car}#*.jpg'"
        result = subprocess.run(command, shell=True, capture_output=True, text=True)

        output = result.stdout.strip().split("\n")
        treated_output = [split[-1].split("#")[-1].replace(".jpg", "") for split in [line.split("/") for line in output]]

        print(", ".join(sorted(treated_output)) + ";")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="verify", formatter_class=argparse.ArgumentDefaultsHelpFormatter)
    parser.add_argument("--path", "-p", type=str, required=True)
    parser.add_argument("--cars", "-c", type=str, required=True)

    main(parser.parse_args())

